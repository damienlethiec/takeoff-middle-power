// The strings the engine (src/engine/index.ts) and the data's small helpers (src/data/copy.ts, effects.ts,
// friends.ts) compose from parts, as English templates. The engine stays language-free: it keeps building these
// strings in English, and the UI finds the template a string came from (src/i18n/match.ts), translates its parts and
// fills the template in the player's language. Keep each template exactly as the engine writes it: a test plays
// seeded games and checks that every string the engine hands the UI is covered (tests/i18n.test.ts).
//
