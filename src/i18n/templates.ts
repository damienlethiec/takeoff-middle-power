//   composed     {a} {b} {list} {card} {cause} {names} {you} {you2}: text that is itself a catalog entry or another
//                template ("Social cohesion 58 → 55, AI safety: …"); {you} and {you2} may also be a number
//   every other  a name or a word that is a catalog entry as it stands: a gauge, a threat, a world, a card, an answer
// Plurals: keys ending in .one / .other (translators may add .few / .many, as Polish needs).

